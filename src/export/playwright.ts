import { volatileKey } from "../diff/volatile";
import { scanPage } from "../drivers/read-fields";
import type { Proof } from "../proof/schema";

/**
 * A standalone Playwright test file that replays every scenario of a proof against a web app and checks the
 * values the proof recorded. Fields are read with the same function Parity uses, labels are compared without
 * case or trailing colons, grid rows by their group, and numbers by value so "69.21 $" equals "$69.21". Fields
 * the proof found noisy are skipped.
 */
export function playwrightSpec(proof: Proof): string {
  const volatile = new Set(proof.volatile);
  const lines: string[] = [
    "// Generated by Parity from a proof. Run with: npx playwright test (baseURL from PARITY_APP_URL).",
    'import { expect, type Page, test } from "@playwright/test";',
    "",
    'test.use({ baseURL: process.env.PARITY_APP_URL ?? "http://127.0.0.1:3000" });',
    "",
    `const scanPage = ${scanPage.toString()};`,
    "",
    'const key = (s: string) => s.replace(/[\\s:]+$/g, "").replace(/\\s+/g, " ").trim().toLowerCase();',
    "const num = (s: string) => {",
    '  const t = s.replace(/[\\s$€£¥]/g, "").replace(/,(?=\\d{3}(\\D|$))/g, "");',
    '  return /^-?\\d+(\\.\\d+)?%?$/.test(t) ? Number(t.replace(/%$/, "")) : null;',
    "};",
    "const same = (a: string, b: string) => {",
    "  const x = num(a);",
    "  const y = num(b);",
    '  return x !== null && y !== null ? x === y : a.replace(/\\s+/g, " ").trim() === b.replace(/\\s+/g, " ").trim();',
    "};",
    "",
    "async function fillField(page: Page, text: string, value: string) {",
    "  const el = (await page.evaluateHandle(scanPage, text)).asElement();",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: text of generated code
    "  if (!el) throw new Error(`no field labelled ${text}`);",
    "  if (await el.evaluate((e) => e instanceof HTMLSelectElement)) await el.selectOption({ label: value });",
    "  else {",
    "    await el.fill(value);",
    "    // Leaving the field fires `change`, which old apps use to look values up on the server.",
    "    await el.evaluate((e) => (e as HTMLElement).blur());",
    "  }",
    '  await page.waitForLoadState("networkidle");',
    "}",
    "",
    "async function press(page: Page, name: string) {",
    '  await page.getByRole("button", { name }).first().click();',
    '  await page.waitForLoadState("networkidle");',
    "}",
    "",
    "// Retried until the screen settles, like a person waiting for the totals to update.",
    "async function expectFields(page: Page, expected: [string, string, string | null][]) {",
    "  await expect(async () => {",
    "    const fields = (await page.evaluate(scanPage)) as { label: string; value: string; group?: string }[];",
    "    for (const [label, value, group] of expected) {",
    "      const found = fields.find((f) => key(f.label) === key(label) && (f.group ?? null) === group);",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: text of generated code
    "      expect(found, `field ${label}`).toBeDefined();",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: text of generated code
    '      expect(same(found?.value ?? "", value), `${label} expected ${value}, got ${found?.value}`).toBe(true);',
    "    }",
    "  }).toPass({ timeout: 5000 });",
    "}",
  ];

  for (const scenario of proof.scenarios) {
    lines.push("", `test(${JSON.stringify(scenario.name)}, async ({ page }) => {`);
    scenario.steps.forEach((step, i) => {
      switch (step.do) {
        case "open":
          lines.push(`  await page.goto(${JSON.stringify(step.path)});`);
          break;
        case "fill":
          lines.push(
            `  await fillField(page, ${JSON.stringify(step.field)}, ${JSON.stringify(step.value)});`,
          );
          break;
        case "click":
          lines.push(`  await press(page, ${JSON.stringify(step.target)});`);
          break;
        case "check": {
          const checkpoint = proof.checkpoints.find((c) => c.scenario === scenario.id && c.step === i);
          const expected = (checkpoint?.screen.fields ?? [])
            .filter((f) => !volatile.has(f.label) && !volatile.has(volatileKey(f, checkpoint?.screen)))
            .map((f) => [f.label, f.value, f.group ?? null]);
          if (step.note) lines.push(`  // ${step.note.replace(/[\r\n\u2028\u2029]+/g, " ")}`);
          lines.push(`  await expectFields(page, ${JSON.stringify(expected)});`);
          break;
        }
      }
    });
    lines.push("});");
  }
  return `${lines.join("\n")}\n`;
}
